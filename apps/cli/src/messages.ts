export const CLI_LOCALES = Object.keys(CLI_CATALOG);
const translate = createTranslator(CLI_CATALOG);

const LIST_TYPES = ['conjunction', 'disjunction', 'plain', 'semicolon'] as const;
const PLAIN_SEPARATOR = ', ';
const SEMICOLON_SEPARATOR = '; ';
const LINE_SEPARATOR = '\n';

export class ListParam {
  readonly items: readonly (string | LocalizedError)[];
  readonly type: (typeof LIST_TYPES)[number];
  readonly kind?: ContentKind;

  constructor(items: readonly (string | LocalizedError)[], type: (typeof LIST_TYPES)[number], kind?: ContentKind) {
    this.items = items;
    this.type = type;
    if (kind !== undefined) this.kind = kind;
  }
}

const listText = (locale: string, { items, type, kind }: ListParam) => {
  const texts = items.map((item) => (item instanceof LocalizedError ? say(locale, item.key, item.params) : item));
  const shown = kind === undefined ? texts : texts.map((item) => contentText(locale, kind, item, item));
  if (type === 'plain' || type === 'semicolon')
    return shown.length === 0
      ? say(locale, 'quickstart.none')
      : shown.join(type === 'plain' ? PLAIN_SEPARATOR : SEMICOLON_SEPARATOR);
  const language = CLI_LOCALES.includes(locale) ? safeLocale(locale) : DEFAULT_LOCALE;
  return new Intl.ListFormat(language, { type }).format(shown);
};

const resolved = (locale: string, value: unknown): unknown => {
  if (value instanceof LocalizedError) return say(locale, value.key, value.params);
  if (value instanceof ListParam) return listText(locale, value);
  if (Array.isArray(value)) return value.map((item) => resolved(locale, item)).join(LINE_SEPARATOR);
  return value;
};

export const say = (locale: string, key: string, params: Params = {}): string =>
  translate(
    locale,
    key,
    Object.fromEntries(Object.entries(params).map(([name, value]) => [name, resolved(locale, value)])),
  );

export class LocalizedError extends Error {
  readonly key: string;
  readonly params: Params;

  constructor(key: string, params: Params = {}) {
    super(say(DEFAULT_LOCALE, key, params));
    this.key = key;
    this.params = params;
  }
}

export const errorText = (locale: string, error: unknown) => {
  if (error instanceof LocalizedError || error instanceof RollReportError) return say(locale, error.key, error.params);
  if (error instanceof ProviderError) return gmFailureText(locale, failureOf(error));
  return error instanceof Error ? error.message : String(error);
};
